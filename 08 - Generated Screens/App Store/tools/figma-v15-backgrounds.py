#!/usr/bin/env python3
"""Rebuild the editable Figma backgrounds of the V.15 App Store slides from the HTML.

    python3 "08 - Generated Screens/App Store/tools/figma-v15-backgrounds.py" > /tmp/v15-bg.js

Prints a script for the Figma MCP `use_figma` tool (file EhpRiGZ5eJnBb132X9zewg, App Screenshot page 338:21544).
It reads the photo boxes and gradient keys straight from screenshots-v15-people.html, so the Figma layers always match
the HTML. For each slide it deletes the slide's `Background` frame and builds a new one:

    Background
      Photo blur      rect, image fill + 8% black, Layer blur 116 (= CSS blur 4.5cqw)
      Photo           clip frame at the HTML photo box
        Fade (mask)   alpha gradient, fades the photo in at the top / out at the bottom
        Image · name  rect sized "cover" (or the HTML background-size) and offset by background-position
      Gradient        51 eased stops of #1d3a27, top to bottom

Then, in order:
  1. run the printed script with use_figma (it returns the new Image + Photo blur node ids, and reuses the image hashes
     already in the file when HASHES below knows them, so no upload is needed for unchanged photos);
  2. for a NEW or changed photo: upload_assets with nodeIds = that slide's Image rect, JPEG from assets/people/;
  3. copy each Image's imageHash into its Photo blur fill (keep the 8% black fill), and add the new hash to HASHES.

WARNING: this rebuild replaces every Background frame. A photo crop or gradient tweak done by hand in Figma is lost.
Sync the hand change back into the HTML first (PHOTOS / scrim keys), then rebuild.
"""
import json, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
HTML = (ROOT / 'screenshots-v15-people.html').read_text()
U, W, H = 12.9, 1290, 2796          # 1cqw at 1290 px wide; slide size
SLIDE_IDS = ["16616:26821", "16616:26836", "16616:26858", "16616:26871", "16616:26886",
             "16616:26901", "16616:26916", "16616:26931", "16616:26946"]
# image hashes already uploaded to the Figma file (24 Nov). Update when a photo is replaced.
HASHES = {
    'dropoff': '5fbe0a714ecd14500d6ce42daf82660d534164c9', 'picnic': '1012dc35393d4249da65ed223f30f88c91a9f8a5',
    'festival': '799d8f1e303f904829295a20c83d26986c9afa7d', 'morning': 'c3ca1478703549313f69fbf90b5bf68799ba705d',
    'kitchen-phone': 'a612473542f6e4d5dfab104222e9b9357aff9420', 'porch': '9889f1899877dd9da56150cf54da2e21bef5cf1a',
    'storytime': '1603f212a871d8e31c857e15d77fda4c2b737e25', 'birthday': '73695a9c3fc88e5dfe8beb773bda07412b0b2c96',
    'pickup': '1be11cb4c4fe03d7ff6be08c56411da76b6bfcfb',
}

def js_array(s):  # the HTML literals are JS (single quotes, .58); make them JSON
    s = re.sub(r"'", '"', s)
    s = re.sub(r"(?<![\d.])\.(\d)", r"0.\1", s)
    return json.loads(s)

block = HTML[HTML.index('const PHOTOS = ['):HTML.index('];', HTML.index('const PHOTOS = ['))]
photos = []
for line in re.findall(r"^\s*\[('[^']+\.webp'.*)\],\s*$", block, re.M):
    photos.append(js_array('[' + line + ']'))
assert len(photos) == 9, f'expected 9 PHOTOS rows, found {len(photos)}'

default_keys = js_array(re.search(r"g\(keys \|\| (\[\[.*?\]\])\)", HTML).group(1))
canopy = js_array(re.search(r"const CANOPY = (\[\[.*?\]\]);", HTML).group(1))
keys = []
for i in range(9):
    call = re.search(r"photoSlide\(%d,(.*?)\) \}," % i, HTML, re.S).group(1)
    explicit = re.search(r"(\[\[[\d., \[\]]*\]\])\s*$", call.strip())
    keys.append(canopy if 'CANOPY' in call else js_array(explicit.group(1)) if explicit else default_keys)

def place(bw, bh, iw, ih, pos, size):
    px, py = [float(v[:-1]) / 100 for v in pos.split()]
    if size: w = bw * float(size.split('%')[0]) / 100; h = w * ih / iw
    else: s = max(bw / iw, bh / ih); w, h = iw * s, ih * s
    return [round((bw - w) * px, 2), round((bh - h) * py, 2), round(w, 2), round(h, 2)]

rows = []
for i, p in enumerate(photos):
    f, pos, _pend, (t, h), *rest = p
    size = rest[0] if rest else None
    name = f.rsplit('.', 1)[0]
    iw, ih = Image.open(ROOT / 'assets' / 'people' / f).size
    by, bh = t * U, h * U
    img = place(W, bh, iw, ih, pos, size)
    bl = place(W + 16 * U, H + 16 * U, iw, ih, pos, None)
    bl = [round(bl[0] - 8 * U, 2), round(bl[1] - 8 * U, 2), bl[2], bl[3]]
    fade_t = round(30 * U, 1) if t > 0 else 0          # HTML: transparent -> #000 30cqw
    fade_b = round(26 * U, 1) if t + h < 216.7 else 0  # HTML: #000 calc(100% - 26cqw) -> transparent
    rows.append([SLIDE_IDS[i], name, round(by, 2), round(bh, 2), img, bl, fade_t, fade_b, i, HASHES.get(name)])

DATA = json.dumps({'R': rows, 'K': keys}, separators=(',', ':'))
print(f"""// generated by tools/figma-v15-backgrounds.py from screenshots-v15-people.html; run with use_figma
const D = {DATA};
const page = figma.root.children.find(p => p.id === '338:21544');
await figma.setCurrentPageAsync(page);
const C = {{ r: 29/255, g: 58/255, b: 39/255 }};
const V = [[0, 1, 0], [-1, 0, 1]]; // top -> bottom
const U = {U}, H = {H};
const stops = keys => {{ const o = []; for (let k = 0; k < keys.length - 1; k++) {{ const [p0, a0] = keys[k], [p1, a1] = keys[k + 1];
  for (let j = 0; j < 10; j++) {{ const t = j / 10, e = t * t * (3 - 2 * t); o.push({{ position: Math.min((p0 + (p1 - p0) * t) * U / H, 1), color: {{ ...C, a: a0 + (a1 - a0) * e }} }}); }} }}
  const [pl, al] = keys[keys.length - 1]; o.push({{ position: Math.min(pl * U / H, 1), color: {{ ...C, a: al }} }}); return o; }};
const black = a => ({{ r: 0, g: 0, b: 0, a }});
const out = [];
for (const [sid, name, top, h, img, bl, fadeT, fadeB, k, hash] of D.R) {{
  const slide = await figma.getNodeByIdAsync(sid);
  for (const c of [...slide.children]) if (c.name === 'Background') c.remove();
  const bg = figma.createFrame(); bg.name = 'Background'; bg.fills = [{{ type: 'SOLID', color: C }}]; bg.clipsContent = true;
  slide.insertChild(0, bg); bg.resize(1290, 2796); bg.x = 0; bg.y = 0;
  const dark = {{ type: 'SOLID', color: {{ r: 0, g: 0, b: 0 }}, opacity: .08 }};
  const photoFill = hash ? {{ type: 'IMAGE', imageHash: hash, scaleMode: 'FILL' }} : {{ type: 'SOLID', color: {{ r: .7, g: .7, b: .7 }} }};
  const blur = figma.createRectangle(); blur.name = 'Photo blur'; bg.appendChild(blur);
  blur.x = bl[0]; blur.y = bl[1]; blur.resize(bl[2], bl[3]);
  blur.fills = [photoFill, dark];
  blur.effects = [{{ type: 'LAYER_BLUR', radius: 116, visible: true }}];
  const box = figma.createFrame(); box.name = 'Photo'; box.fills = []; box.clipsContent = true; bg.appendChild(box);
  box.x = 0; box.y = top; box.resize(1290, h);
  if (fadeT || fadeB) {{
    const m = figma.createRectangle(); m.name = 'Fade (mask)'; box.appendChild(m);
    m.resize(1290, h); m.x = 0; m.y = 0;
    const st = [{{ position: 0, color: black(fadeT ? 0 : 1) }}];
    if (fadeT) st.push({{ position: fadeT / h, color: black(1) }});
    if (fadeB) st.push({{ position: 1 - fadeB / h, color: black(1) }});
    st.push({{ position: 1, color: black(fadeB ? 0 : 1) }});
    m.fills = [{{ type: 'GRADIENT_LINEAR', gradientTransform: V, gradientStops: st }}];
    m.isMask = true; m.maskType = 'ALPHA';
  }}
  const im = figma.createRectangle(); im.name = 'Image · ' + name; box.appendChild(im);
  im.x = img[0]; im.y = img[1]; im.resize(img[2], img[3]);
  im.fills = [photoFill];
  const gr = figma.createRectangle(); gr.name = 'Gradient'; bg.appendChild(gr);
  gr.resize(1290, 2796); gr.x = 0; gr.y = 0;
  gr.fills = [{{ type: 'GRADIENT_LINEAR', gradientTransform: V, gradientStops: stops(D.K[k]) }}];
  out.push({{ slide: k + 1, name, img: im.id, blur: blur.id, needsUpload: !hash }});
}}
return out;""")
print(f'// {len(rows)} slides; photos without a known hash: {[r[1] for r in rows if not r[9]]}', file=sys.stderr)
