"""Build the Sprout Assist review site from app/ plus the approved SSC Kids demo's CSS.

The SSC demo (ssc-kids-signup-demo/prototype/index.html) is the design authority. Its <style> block is
copied in verbatim at build time, so this prototype can never drift from it. app/app.css only adds the
Assist home (Figma A·1 14892:33659) and thin variants of SSC parts.

    python3 build.py          # writes site/
    cd site && vercel deploy --prod --yes
"""
from pathlib import Path
import json, re, shutil
from PIL import Image

HERE = Path(__file__).resolve().parent
APP = HERE / 'app'
SSC = HERE.parent / 'ssc-kids-signup-demo/prototype/index.html'
SITE = HERE / 'site'

ROUTES = ['assist', 'sports', 'summer-camps', 'own-sitters', 'class-families', 'night-out',
          'birthdays', 'birthday-invite', 'create-event', 'create-club', 'accounts-payments',
          'date-night-a', 'date-night-b', 'date-night-c', 'date-night-v2',
          'sitter-v3', 'sitter-v3-class', 'sitter-v3-none', 'sitter-v3-share', 'date-night-v3',
          'sitter-when-a', 'sitter-when-b', 'sitter-class-chat',
          'sitter-profile',
          'playdate', 'playdate-new-time', 'playdate-cant', 'playdate-invite',
          'ui-a', 'ui-b', 'ui-c', 'pay-todo', 'happening-am', 'happening-pm',
          'book-a-sitter', 'book-a-sitter-saved', 'plan-a-date-night', 'booked-evening', 'chat-history', 'add-account', 'assist-ongoing', 'after-school', 'tutoring',
          'carpool-a', 'carpool-b', 'plan-carpool']

ssc = SSC.read_text()
css = re.search(r'<style>(.*?)</style>', ssc, re.S).group(1)
css = css.replace('url(assets/', 'url(/assets/')
page = (APP / 'index.html').read_text().replace('<!--SSC_CSS-->', '<style>\n/* copied from ssc-kids-signup-demo/prototype/index.html */' + css + '</style>')
import time
v = str(int(time.time()))
for f in ['app.css', 'app.js', 'flows.js', 'date-night.js', 'date-night-map.js', 'date-night-map.css', 'sitter-v3.js', 'sitter-v3.css', 'ui-directions.js', 'ui-directions.css', 'assets/navbar-motion.js', 'assets/navbar-motion.css']:
    page = page.replace(f'"/{f}"', f'"/{f}?v={v}"')

# clean rebuild, keep the Vercel project link
keep = SITE / '.vercel'
if SITE.exists():
    for p in SITE.iterdir():
        if p != keep:
            shutil.rmtree(p) if p.is_dir() else p.unlink()
SITE.mkdir(exist_ok=True)
(SITE / 'index.html').write_text(page)
for r in ROUTES:
    (SITE / r).mkdir(exist_ok=True)
    (SITE / r / 'index.html').write_text(page)
# J4: publish only the class chat chrome, without the conversation in the reference.
with Image.open(HERE / 'research/ref-2026-11-18/class-chat-CHAT-10-8728-99165.png') as chat:
    chat.crop((0, 0, 393, 265)).save(SITE / 'sitter-class-chat/header.png')
    chat.crop((0, 750, 393, 852)).save(SITE / 'sitter-class-chat/composer.png')
for f in ['app.css', 'app.js', 'flows.js', 'date-night.js', 'date-night-map.js', 'date-night-map.css', 'sitter-v3.js', 'sitter-v3.css', 'ui-directions.js', 'ui-directions.css']:
    shutil.copy2(APP / f, SITE / f)
# B3 review: the three date night directions side by side
(SITE / 'date-night').mkdir(exist_ok=True)
(SITE / 'date-night-live').mkdir(exist_ok=True)
(SITE / 'date-night-live' / 'index.html').write_text((APP / 'live-night.html').read_text())
(SITE / 'assist-map').mkdir(exist_ok=True)
(SITE / 'assist-map' / 'index.html').write_text((APP / 'assist-map.html').read_text())
if (APP / 'sprout-map.html').exists():   # I1 (17 Nov): whole-Sprout map; data is generated by tools/build-sprout-map.py
    (SITE / 'sprout-map').mkdir(exist_ok=True)
    (SITE / 'sprout-map' / 'index.html').write_text((APP / 'sprout-map.html').read_text())
    if (APP / 'sprout-map-data.js').exists(): shutil.copy2(APP / 'sprout-map-data.js', SITE / 'sprout-map-data.js')
# 20 Nov (Ahmad): both sides of a request, for presenting; /receiver/?v=... is the other parent's (or sitter's) phone
(SITE / 'other-side').mkdir(exist_ok=True)
(SITE / 'other-side' / 'index.html').write_text((APP / 'other-side.html').read_text())
(SITE / 'receiver').mkdir(exist_ok=True)
(SITE / 'receiver' / 'index.html').write_text((APP / 'receiver.html').read_text())
(SITE / 'sitter-reply').mkdir(exist_ok=True)
(SITE / 'sitter-reply' / 'index.html').write_text((APP / 'sitter-reply.html').read_text())
(SITE / 'sitter-profile' / 'index.html').write_text((APP / 'sitter-profile.html').read_text())
(SITE / 'ui-directions').mkdir(exist_ok=True)
(SITE / 'ui-directions' / 'index.html').write_text((APP / 'ui-review.html').read_text())
# K1 (18 Nov): Assist home, Uber-style services grid, current vs A vs B
(SITE / 'assist-home').mkdir(exist_ok=True)
(SITE / 'assist-home' / 'index.html').write_text((APP / 'home-review.html').read_text())
# L2 (19 Nov): the one link for Tony, every flow from its start
(SITE / 'review').mkdir(exist_ok=True)
(SITE / 'review' / 'index.html').write_text((APP / 'review.html').read_text())
# M3 (19 Nov): carpool directions A + B side by side, review only until Ahmad picks one
(SITE / 'carpool').mkdir(exist_ok=True)
(SITE / 'carpool' / 'index.html').write_text((APP / 'carpool-review.html').read_text())
# Ahmad (19 Nov): the pre-M2 page with every review state, private, not linked from /review/
(SITE / 'review-all').mkdir(exist_ok=True)
(SITE / 'review-all' / 'index.html').write_text((APP / 'review-all.html').read_text())
(SITE / 'sitter-date-night').mkdir(exist_ok=True)
(SITE / 'sitter-date-night' / 'index.html').write_text((APP / 'sitter-review.html').read_text())
(SITE / 'date-night' / 'index.html').write_text((APP / 'date-night-review.html').read_text().replace('?v=0', '?v=' + v))
shutil.copytree(APP / 'assets', SITE / 'assets')
(SITE / 'vercel.json').write_text(json.dumps({'cleanUrls': True, 'trailingSlash': True,
    'headers': [{'source': '/(.*)', 'headers': [{'key': 'X-Robots-Tag', 'value': 'noindex, nofollow'}]}]}))
print(f'Built {SITE}: {len(ROUTES) + 1} routes')
